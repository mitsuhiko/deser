impl<T: Sync, A: SerializeAs<T>, const N: usize> IndexedSeq for SerializeAsRef<[A; N], [T; N]> {
    #[inline]
    fn element(
        &self,
        index: usize,
        _state: &mut State,
    ) -> Result<Option<SerializeHandle<'_>>, Error> {
        Ok(self.get().get(index).map(handle_as::<A, T>))
    }
}

impl<T: Sync, A: SerializeAs<T>, const N: usize> SerializeAs<[T; N]> for [A; N] {
    fn serialize_as<'a>(value: &'a [T; N], state: &mut State) -> Result<Chunk<'a>, Error> {
        Ok(match A::__private_slice_as_bytes_as(value) {
            Some(bytes) => Chunk::Atom(Atom::Bytes(Bytes::new(bytes))),
            None => Chunk::seq(
                IndexedSeqEmitter::new(SerializeAsRef::<[A; N], [T; N]>::new(value)),
                state,
            ),
        })
    }

    fn container_shape_as(value: &[T; N]) -> ContainerShape {
        ContainerShape::new().with_len(value.len())
    }

    #[inline]
    fn __private_begin_as<'a>(value: &'a [T; N], _state: &mut State) -> Result<Begin<'a>, Error> {
        let shape = Self::container_shape_as(value);
        Ok(match A::__private_slice_as_bytes_as(value) {
            Some(bytes) => Begin::chunk(Chunk::Atom(Atom::Bytes(Bytes::new(bytes))), shape, false),
            None => Begin::indexed_seq(SerializeAsRef::<[A; N], [T; N]>::new(value), shape),
        })
    }
}

impl<T: Sync, A: SerializeAs<T>> SerializeAs<[T]> for [A] {
    fn serialize_as<'a>(value: &'a [T], state: &mut State) -> Result<Chunk<'a>, Error> {
        Ok(match A::__private_slice_as_bytes_as(value) {
            Some(bytes) => Chunk::Atom(Atom::Bytes(Bytes::new(bytes))),
            None => Chunk::seq(
                IterEmitter::<'_, _, A>(value.iter(), core::marker::PhantomData),
                state,
            ),
        })
    }

    fn container_shape_as(value: &[T]) -> ContainerShape {
        ContainerShape::new().with_len(value.len())
    }

    #[inline]
    fn __private_begin_as<'a>(value: &'a [T], state: &mut State) -> Result<Begin<'a>, Error> {
        let shape = Self::container_shape_as(value);
        Ok(Begin::chunk(
            Self::serialize_as(value, state)?,
            shape,
            false,
        ))
    }
}

/// Implements `SerializeAs` for maps with key and value adapters.
///
/// The maps need to support `len` and `iter`.
macro_rules! serialize_as_map {
    ($([$($gen:tt)*] $ty:ty => $adapter:ty, $order:ident;)*) => {
        $(
            impl<$($gen)*> $crate::adapters::SerializeAs<$ty> for $adapter
            where
                K: Sync,
                V: Sync,
                KA: $crate::adapters::SerializeAs<K>,
                VA: $crate::adapters::SerializeAs<V>,
            {
                fn serialize_as<'a>(
                    value: &'a $ty,
                    state: &mut $crate::State,
                ) -> Result<$crate::ser::Chunk<'a>, $crate::Error> {
                    Ok($crate::ser::Chunk::map($crate::adapters::ser_impls::MapIterEmitter::<_, V, KA, VA> {
                            iter: value.iter(),
                            value: None,
                            _marker: core::marker::PhantomData,
                        }, state))
                }

                fn container_shape_as(value: &$ty) -> $crate::ContainerShape {
                    $crate::ContainerShape::new()
                        .with_order($crate::Order::$order)
                        .with_len(value.len())
                }

                #[inline]
                fn __private_begin_as<'a>(
                    value: &'a $ty,
                    state: &mut $crate::State,
                ) -> Result<$crate::ser::Begin<'a>, $crate::Error> {
                    let shape = Self::container_shape_as(value);
                    Ok($crate::ser::Begin::chunk(
                        Self::serialize_as(value, state)?,
                        shape,
                        false,
                    ))
                }
            }
        )*
    };
}

